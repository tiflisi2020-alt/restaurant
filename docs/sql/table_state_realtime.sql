-- Restaurant Tiflis — shared table state migration
-- Run this script once in Supabase SQL Editor.
-- It does not delete reservations or existing table data.
-- After running it, the frontend code must be updated to read/write these tables.

begin;

-- 1) Banquet / merged table groups
create table if not exists public.table_groups (
  id uuid primary key default gen_random_uuid(),
  group_code text not null unique,
  name text not null,
  table_ids text[] not null default '{}',
  status text not null default 'merged'
    check (status in ('merged', 'cleaning', 'blocked', 'released')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint table_groups_min_two_tables check (cardinality(table_ids) >= 2)
);

create index if not exists table_groups_status_idx
  on public.table_groups (status);

create index if not exists table_groups_table_ids_gin_idx
  on public.table_groups using gin (table_ids);

-- 2) Daily operational state for each physical table
-- One row per table and business day. This is separate from tables.status,
-- because 'occupied', 'cleaning' and 'free' are daily floor operations.
create table if not exists public.table_operations (
  table_id text not null,
  business_date date not null default ((now() at time zone 'Asia/Tbilisi')::date),
  status text not null
    check (status in ('free', 'occupied', 'cleaning', 'blocked')),
  guest_name text,
  guests integer check (guests is null or guests between 1 and 99),
  source text not null default 'walk-in'
    check (source in ('walk-in', 'reservation', 'admin', 'system')),
  reservation_id text,
  seated_at timestamptz,
  updated_at timestamptz not null default now(),
  updated_by text,
  primary key (table_id, business_date)
);

create index if not exists table_operations_date_status_idx
  on public.table_operations (business_date, status);

create index if not exists table_operations_reservation_idx
  on public.table_operations (reservation_id);

-- 3) Central audit history for table and reservation actions
create table if not exists public.table_audit_log (
  id bigint generated by default as identity primary key,
  action text not null,
  table_ids text[] not null default '{}',
  group_code text,
  reservation_id text,
  actor text,
  details jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create index if not exists table_audit_log_created_at_idx
  on public.table_audit_log (created_at desc);

create index if not exists table_audit_log_action_idx
  on public.table_audit_log (action);

-- Keep updated_at current when a row is edited.
create or replace function public.set_table_state_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists table_groups_set_updated_at on public.table_groups;
create trigger table_groups_set_updated_at
before update on public.table_groups
for each row execute function public.set_table_state_updated_at();

drop trigger if exists table_operations_set_updated_at on public.table_operations;
create trigger table_operations_set_updated_at
before update on public.table_operations
for each row execute function public.set_table_state_updated_at();

-- RLS is enabled, with policies matching the current public app architecture.
-- For stronger production security, replace anon write policies with authenticated
-- admin policies after admin authentication is moved to Supabase Auth.
alter table public.table_groups enable row level security;
alter table public.table_operations enable row level security;
alter table public.table_audit_log enable row level security;

drop policy if exists table_groups_anon_select on public.table_groups;
create policy table_groups_anon_select
on public.table_groups for select to anon using (true);

drop policy if exists table_groups_anon_insert on public.table_groups;
create policy table_groups_anon_insert
on public.table_groups for insert to anon with check (true);

drop policy if exists table_groups_anon_update on public.table_groups;
create policy table_groups_anon_update
on public.table_groups for update to anon using (true) with check (true);

drop policy if exists table_groups_anon_delete on public.table_groups;
create policy table_groups_anon_delete
on public.table_groups for delete to anon using (true);

drop policy if exists table_operations_anon_select on public.table_operations;
create policy table_operations_anon_select
on public.table_operations for select to anon using (true);

drop policy if exists table_operations_anon_insert on public.table_operations;
create policy table_operations_anon_insert
on public.table_operations for insert to anon with check (true);

drop policy if exists table_operations_anon_update on public.table_operations;
create policy table_operations_anon_update
on public.table_operations for update to anon using (true) with check (true);

drop policy if exists table_operations_anon_delete on public.table_operations;
create policy table_operations_anon_delete
on public.table_operations for delete to anon using (true);

drop policy if exists table_audit_log_anon_select on public.table_audit_log;
create policy table_audit_log_anon_select
on public.table_audit_log for select to anon using (true);

drop policy if exists table_audit_log_anon_insert on public.table_audit_log;
create policy table_audit_log_anon_insert
on public.table_audit_log for insert to anon with check (true);

grant select, insert, update, delete on table public.table_groups to anon, authenticated;
grant select, insert, update, delete on table public.table_operations to anon, authenticated;
grant select, insert on table public.table_audit_log to anon, authenticated;
grant usage, select on sequence public.table_audit_log_id_seq to anon, authenticated;

-- Enable Supabase Realtime for cross-device table synchronization.
do $$
begin
  alter publication supabase_realtime add table public.table_groups;
exception
  when duplicate_object then null;
end $$;

do $$
begin
  alter publication supabase_realtime add table public.table_operations;
exception
  when duplicate_object then null;
end $$;

do $$
begin
  alter publication supabase_realtime add table public.table_audit_log;
exception
  when duplicate_object then null;
end $$;

commit;

